/** Deterministic procedural loop for circuits without hand-drawn art. */
function proceduralLoop(circuitId: string): readonly Point[] {
  // simple string hash → seeded pseudo-random radius wobble
  let seed = 0;
  for (let i = 0; i < circuitId.length; i++) {
    seed = (seed * 31 + circuitId.charCodeAt(i)) >>> 0;
  }
  const rand = (): number => {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 0xffffffff;
  };
  const n = 12 + Math.floor(rand() * 5);
  const pts: Point[] = [];
  for (let i = 0; i < n; i++) {
    const angle = (i / n) * Math.PI * 2;
    const radius = 20 + rand() * 10;
    pts.push([
      50 + Math.cos(angle) * radius,
      52 + Math.sin(angle) * radius * 0.86,
    ]);
  }
  return pts;
}

export function trackLoop(circuitId: string): readonly Point[] {
  return TRACK_LOOPS[circuitId] ?? proceduralLoop(circuitId);
}

/** Path `d` for a circuit silhouette. mul scales the 0..100 box. */
export function trackPath(circuitId: string, mul = 1): string {
  return smoothLoop(trackLoop(circuitId), mul);
}

