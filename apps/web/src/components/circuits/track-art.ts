// ─────────────────────────────────────────────────────────────────────────────
// Grand Tour — stylised track silhouettes (cosmetic imagery only).
//
// These point-loops are hand-drawn ART from the design bundle, not circuit
// data: they are decorative signatures "not to scale", the same category as
// placeholder imagery (allowed per CLAUDE.md). Coordinates live in a
// normalised 0..100 box and are smoothed into closed beziers at runtime.
// Unknown circuits get a deterministic procedural loop so nothing breaks
// when the calendar changes.
// ─────────────────────────────────────────────────────────────────────────────

export type Point = readonly [number, number];

/** Catmull-Rom → closed cubic bezier path (same technique as the homepage). */
export function smoothLoop(points: readonly Point[], mul = 1): string {
  const n = points.length;
  if (n < 3) return '';
  const at = (i: number): Point => points[((i % n) + n) % n] ?? [0, 0];
  const first = at(0);
  let d = `M ${(first[0] * mul).toFixed(2)} ${(first[1] * mul).toFixed(2)} `;
  for (let i = 0; i < n; i++) {
    const a = at(i - 1);
    const b = at(i);
    const c = at(i + 1);
    const e = at(i + 2);
    const c1x = (b[0] + (c[0] - a[0]) / 6) * mul;
    const c1y = (b[1] + (c[1] - a[1]) / 6) * mul;
    const c2x = (c[0] - (e[0] - b[0]) / 6) * mul;
    const c2y = (c[1] - (e[1] - b[1]) / 6) * mul;
    d += `C ${c1x.toFixed(2)} ${c1y.toFixed(2)}, ${c2x.toFixed(2)} ${c2y.toFixed(2)}, ${(c[0] * mul).toFixed(2)} ${(c[1] * mul).toFixed(2)} `;
  }
  return `${d}Z`;
}

